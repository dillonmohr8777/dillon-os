HEAD = ('<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" '
        'fill="none" stroke="currentColor" stroke-width="1.7" '
        'stroke-linecap="round" stroke-linejoin="round">')


def normalise(body):
    return ' '.join(body.split())


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    table = {}
    for name, body in ICONS.items():
        body = normalise(body)
        table[name] = body
        (OUT / f'{name}.svg').write_text(f'{HEAD}{body}</svg>\n')
    JS.parent.mkdir(parents=True, exist_ok=True)
    JS.write_text('/* generated by icons.py, do not edit */\n'
                  'const ICONS = ' + json.dumps(table, indent=0) + ';\n')
    print(f'{len(table)} icons -> {OUT.relative_to(HERE)}/ and {JS.relative_to(HERE)}')


if __name__ == '__main__':
    main()
