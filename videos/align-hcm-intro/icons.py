"""Draw the Align HCM service icon set.

One monoline family on a 24 unit grid, 1.7 stroke, round caps and joins, no
fills. Everything is stroked in currentColor so a single file works orange on
navy, white on navy, or ink on cream without a second export.

Writes assets/icons/<name>.svg plus build/icons.js, a plain object of raw path
markup that build.py inlines into index.html.

    python3 icons.py
"""
