describe('browser-access router', () => {
  const CLI = path.join(VAULT, '_os', 'automation', 'bin', 'browser-access.js');

  it('probe records never-9222 and writes regenerable state', () => {
    const raw = execFileSync(process.execPath, [CLI, 'probe'], {
      cwd: VAULT,
      encoding: 'utf8',
    });
    const out = JSON.parse(raw);
    assert.deepEqual(out.never_ports, [9222]);
    assert.equal(out.evidence_port, 9223);
    const ids = out.engines.map((e) => e.id);
    assert.ok(ids.includes('chrome_isolated'));
    assert.ok(ids.includes('camofox'));
    assert.ok(ids.includes('firecrawl'));
    assert.ok(ids.includes('playwright_mcp'));
    assert.equal(out.engines.find((e) => e.id === 'bright_data').live, false);
    const pw = out.engines.find((e) => e.id === 'playwright_mcp');
    if (pw.live) {
      assert.match(pw.detail, /8931/);
      assert.match(pw.detail, /no --extension/);
    }
    const src = read('_os/automation/bin/browser-access.js');
    assert.match(src, /never.*9222/i);
    assert.doesNotMatch(src, /remote-debugging-port=9222/);
    assert.match(src, /EVIDENCE_PORT/);
    assert.match(src, /start-playwright/);
    assert.doesNotMatch(src, /args\.push\('--extension'\)/);
  });

  it('recommend returns job-specific engine order', () => {
    const cloudflare = JSON.parse(execFileSync(process.execPath, [CLI, 'recommend', 'cloudflare'], {
      cwd: VAULT,
      encoding: 'utf8',
    }));
    assert.deepEqual(cloudflare.order, ['firecrawl_stealth', 'camofox', 'playwright_mcp']);
    const logged = JSON.parse(execFileSync(process.execPath, [CLI, 'recommend', 'logged_in'], {
      cwd: VAULT,
      encoding: 'utf8',
    }));
    assert.deepEqual(logged.order, ['claude_in_chrome']);
    const js = JSON.parse(execFileSync(process.execPath, [CLI, 'recommend', 'js_interact'], {
      cwd: VAULT,
      encoding: 'utf8',
    }));
    assert.equal(js.order[0], 'playwright_mcp');
    const policy = JSON.parse(read('System/browser-access.policy.json'));
    assert.deepEqual(policy.never.ports, [9222]);
    assert.equal(policy.chrome.evidence_port, 9223);
    assert.deepEqual(policy.playwright_mcp.never_flags, ['--extension']);
    assert.equal(policy.playwright_mcp.args.includes('--extension'), false);
    assert.equal(policy.jobs.js_interact[0], 'playwright_mcp');
    assert.equal(policy.jobs.screenshot[0], 'playwright_mcp');
  });

  it('fetch of a local file uses isolated Chrome, not 9222', () => {
    const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'ba-'));
    const htmlPath = path.join(tmp, 'page.html');
    fs.writeFileSync(htmlPath, '<!doctype html><title>Router Fixture</title><p>ok</p>');
    const profile = path.join(tmp, 'profile');
    const raw = execFileSync(process.execPath, [CLI, 'fetch', `file://${htmlPath}`], {
      cwd: VAULT,
      encoding: 'utf8',
      timeout: 25000,
      env: { ...process.env, BROWSER_EVIDENCE_PROFILE: profile },
    });
    const out = JSON.parse(raw);
    assert.equal(out.engine, 'chrome_isolated');
    assert.equal(out.title, 'Router Fixture');
    assert.equal(String(out.binary).includes('google-chrome') && !String(out.binary).includes('/opt/google/chrome/chrome'), false);
  });

  it('fetch of https uses isolated Playwright MCP, not --extension', () => {
    const raw = execFileSync(process.execPath, [CLI, 'fetch', 'https://example.com'], {
      cwd: VAULT,
      encoding: 'utf8',
      timeout: 25000,
    });
    const out = JSON.parse(raw);
    assert.equal(out.engine, 'playwright_mcp');
    assert.equal(out.title, 'Example Domain');
    assert.match(out.endpoint, /localhost:8931/);
  });
});

describe('owned browser history ingest', () => {
  it('sanitizes titles/domains, drops login paths, and refuses non-private output', () => {
    const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'hist-'));
    const db = path.join(tmp, 'History');
    const out = path.join(tmp, 'out');
    const py = `
import datetime, sqlite3, os
db = os.environ['HIST_DB']
conn = sqlite3.connect(db)
conn.execute('CREATE TABLE urls (id INTEGER PRIMARY KEY, url LONGVARCHAR, title LONGVARCHAR, visit_count INTEGER, typed_count INTEGER, last_visit_time INTEGER, hidden INTEGER DEFAULT 0)')
epoch = datetime.datetime(1601,1,1)
now = datetime.datetime.now(datetime.timezone.utc).replace(tzinfo=None)
micro = int((now - epoch).total_seconds() * 1e6)
rows = [
  ('https://example.com/pricing?token=secret', 'Example pricing', 3, micro),
  ('https://accounts.google.com/signin', 'Sign in', 9, micro),
  ('https://bankofamerica.com/login', 'Bank', 2, micro),
  ('https://shadowhvac.example/ac-repair', 'AC repair', 1, micro),
]
conn.executemany('INSERT INTO urls (url,title,visit_count,typed_count,last_visit_time,hidden) VALUES (?,?,?,0,?,0)', rows)
conn.commit()
`;
    execFileSync('python3', ['-c', py], {
      cwd: VAULT,
      env: { ...process.env, HIST_DB: db },
    });

    const exported = execFileSync('python3', [HISTORY, '--db', db, '--out', out, '--days', '14'], {
      cwd: VAULT,
      encoding: 'utf8',
      env: { ...process.env, BROWSER_HISTORY_TEST: '1' },
    });
    assert.match(exported, /rows=/);
    const files = fs.readdirSync(out).filter((f) => f.endsWith('.md'));
    assert.equal(files.length, 1);
    const body = fs.readFileSync(path.join(out, files[0]), 'utf8');
    assert.match(body, /example\.com/);
    assert.match(body, /shadowhvac\.example/);
    assert.doesNotMatch(body, /token=secret/);
    assert.doesNotMatch(body, /accounts\.google\.com/);
    assert.doesNotMatch(body, /bankofamerica/);

    let refused = false;
    try {
      execFileSync('python3', [HISTORY, '--db', db, '--out', path.join(tmp, 'leaked'), '--days', '1'], {
        cwd: VAULT,
        encoding: 'utf8',
        env: { ...process.env, BROWSER_HISTORY_TEST: '' },
      });
    } catch (err) {
      refused = true;
      assert.match(String(err.stderr || err.stdout || err), /refusing to write/);
    }
    assert.equal(refused, true);
  });
});
