/**
 * Contracts for the web ladder, camofox clone helper, owned-history ingest,
 * and the Claude-agent generator. Run: node --test _os/test/web-stack.test.js
 */
const { describe, it } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { execFileSync } = require('node:child_process');
const crypto = require('node:crypto');

const VAULT = path.resolve(__dirname, '..', '..');
const AGENTS_DIR = path.join(VAULT, '.claude', 'agents');
const AGENT_NAMES = [
  'marketing-chief',
  'web-product-builder',
  'qa-critic',
  'paid-media-analyst',
  'growth-content',
  'brain-curator',
  'reliability-scout',
];
const GENERATOR = path.join(VAULT, 'System', 'scripts', 'Build-ClaudeAgents.py');
const CLONE = path.join(VAULT, 'System', 'scripts', 'Clone-CamofoxBrowser.py');
const HISTORY = path.join(VAULT, 'System', 'scripts', 'Export-BrowserHistory.py');

function read(rel) {
  return fs.readFileSync(path.join(VAULT, rel), 'utf8');
}

function hashDir(dir) {
  const h = crypto.createHash('sha256');
  for (const name of fs.readdirSync(dir).sort()) {
    if (!name.endsWith('.md')) continue;
    h.update(name);
    h.update(fs.readFileSync(path.join(dir, name)));
  }
  return h.digest('hex');
}

