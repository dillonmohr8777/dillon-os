describe('Claude agent generator', () => {
  it('emits seven agents with ladder, recursion, and local-stack grant', () => {
    for (const name of AGENT_NAMES) {
      const text = fs.readFileSync(path.join(AGENTS_DIR, `${name}.md`), 'utf8');
      assert.match(text, /GENERATED by System\/scripts\/Build-ClaudeAgents\.py/);
      assert.match(text, /FIRECRAWL_BATCH_SCRAPE/);
      assert.match(text, /earned-lessons\.md/);
      assert.match(text, /Clone-CamofoxBrowser\.py/);
      assert.match(text, /Export-BrowserHistory\.py/);
      assert.match(text, /does \*\*not\*\* unlock outbound verbs/);
      assert.match(text, /start-playwright/);
      assert.doesNotMatch(text, /Not cloned locally yet/);
      assert.doesNotMatch(text, /installed, \*\*not live\*\*/);
      assert.doesNotMatch(text, /\| 4 \| Firecrawl with `proxy: "stealth"` \|/);
    }
  });

  it('is idempotent', () => {
    const before = hashDir(AGENTS_DIR);
    execFileSync('python3', [GENERATOR], { cwd: VAULT, encoding: 'utf8' });
    const after = hashDir(AGENTS_DIR);
    assert.equal(after, before);
  });
});

